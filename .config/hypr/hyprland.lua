local function wallust_color(name, fallback)
    local path = HOME .. "/.cache/wallust/colors-hyprland.conf"
    local f = io.open(path, "r")
    if not f then
        return fallback
    end
    local value
    for line in f:lines() do
        local n, v = line:match("^%s*%$([%w_]+)%s*=%s*(%S+)")
        if n == name then
            value = v
            break
        end
    end
    f:close()
    return value or fallback
end

