-- Startup -------------------------------------------------------------------
hl.on("hyprland.start", function()
    local commands = {
        "dbus-update-activation-environment --systemd WAYLAND_DISPLAY XDG_CURRENT_DESKTOP HYPRLAND_INSTANCE_SIGNATURE",
        "systemctl --user restart xdg-desktop-portal-hyprland xdg-desktop-portal",
        "wl-paste --type text --watch cliphist store",
        "wl-paste --type image --watch cliphist store",
        "hyprpolkitagent",
        "hypridle",
        "start-navbar",
        "hyprsunset",
        "swaync",
        "nm-applet --indicator",
        "hypr-nice",
        "awww-daemon",
        "sleep 1 && awww restore || true",
        "bash ~/.config/hypr/scripts/wallpapers/check-video.sh",
    }

    for _, command in ipairs(commands) do
        run(command)
    end
end)

-- Active NKS window skin. customize windows writes this state file and reloads Hyprland.
local skin_name = "legacy"
local skin_state = HOME .. "/.cache/nekoroshell/window_skin"
local sf = io.open(skin_state, "r")
if sf then
    local value = sf:read("*l")
    sf:close()
    if value and value:match("^[%w_-]+$") then
        local candidate = HOME .. "/.config/hypr/nks-window-skins/" .. value .. ".lua"
        local cf = io.open(candidate, "r")
        if cf then
            cf:close()
            skin_name = value
        end
    end
end
local skin_file = HOME .. "/.config/hypr/nks-window-skins/" .. skin_name .. ".lua"
local sf2 = io.open(skin_file, "r")
if sf2 then
    sf2:close()
    dofile(skin_file)
end

